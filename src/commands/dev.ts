export interface DevOptions {
  cwd?: string;
  command?: string[];
  skipTrust?: boolean;
  infra?: boolean;
  skipInfra?: boolean;
  noExit?: boolean;
  caddyPath?: string;
  systemCaddy?: boolean;
}

export interface DevPorts {
  httpsPort: number;
  httpPort: number;
}

/** Порт по умолчанию для чистых URL (без `:порт` в адресной строке). */
export const DEFAULT_HTTPS_PORT = 443;
export const DEFAULT_HTTP_PORT = 80;
/** Непривилегированный откат, если 443/80 заняты или требуют прав. */
export const FALLBACK_HTTPS_PORT = 8443;
export const FALLBACK_HTTP_PORT = 8080;

export interface DevCaddyfileOptions {
  /**
   * Установлен ли локальный Root CA в доверенные ОС (`pegas ca install`).
   * false (по умолчанию) -> генерируем skip_install_trust: Caddy не должен
   * сам пытаться ставить сертификат через sudo посреди dev-сессии — на WSL
   * это ещё и бесполезно (браузер живёт в Windows, а Caddy лезет в Linux NSS).
   */
  caTrusted?: boolean;
}

export function generateDevCaddyfile(
  contract: PegasContract,
  ports: DevPorts = { httpsPort: DEFAULT_HTTPS_PORT, httpPort: DEFAULT_HTTP_PORT },
  options: DevCaddyfileOptions = {}
): string {
  const adminLine = contract.devGateway?.admin ? "" : "    admin off\n";
  // Безопасное умолчание: НЕ позволяем Caddy лезть в системный trust store
  // (sudo-промпт посреди dev). skip_install_trust убирается только при явном
  // отказе в контракте (skipInstallTrust: false) И установленном CA.
  const skipTrust = !(contract.devGateway?.skipInstallTrust === false && options.caTrusted === true);
  const trustLine = skipTrust ? "    skip_install_trust\n" : "";
  const globalBlock = `{\n${adminLine}    http_port ${ports.httpPort}\n    https_port ${ports.httpsPort}\n${trustLine}}`;
  const blocks: string[] = [globalBlock];

  const services = contract.services || {};
  for (const [, serviceConfig] of Object.entries(services)) {
    const devDomains = getEnvironmentDomains(serviceConfig, "development");
    if (!Array.isArray(devDomains) || devDomains.length === 0) {
      continue;
    }

    const port = String(getServicePort(serviceConfig));

    const domainList = devDomains
      .map((d) => d.trim())
      .filter(Boolean)
      .join(", ");
    if (!domainList) continue;

    blocks.push(`${domainList} {\n    reverse_proxy localhost:${port}\n}`);
  }

  if (blocks.length === 1) {
    let fallbackPort = 3000;
    for (const serviceConfig of Object.values(services)) {
      fallbackPort = getServicePort(serviceConfig);
      break;
    }
    blocks.push(`app.localhost {\n    reverse_proxy localhost:${fallbackPort}\n}`);
  }

  return `# Auto-generated by pegas dev. Do not edit manually.\n\n` + blocks.join("\n\n") + "\n";
}


async function handleDockerRuntimeDev(
  contract: PegasContract,
  projectRoot: string,
  options: DevOptions
): Promise<void> {
  const projectName = contract.projectName || path.basename(projectRoot);
  const projectId = getProjectRuntimeId(projectRoot, projectName);
  const generated = createRuntimeCompose(contract, { projectRoot, projectId, environment: "development" });

  const fail = (message: string) => {
    console.error(message);
    if (!options.noExit) process.exit(1);
  };

  let containerIds: string[];
  try {
    const listed = child_process.execFileSync("docker", [
      "ps", "-aq", "--filter", "label=pegas.project=" + projectId,
    ], { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
    containerIds = listed.trim().split(/\s+/).filter(Boolean);
  } catch (error: any) {
    fail(`❌ Docker is unavailable or the daemon cannot be reached: ${error.message}`);
    return;
  }

  if (containerIds.length === 0) {
    fail("❌ Docker development environment is not deployed. Run 'pegas deploy development' first.");
    return;
  }

  let containers: any[];
  try {
    containers = JSON.parse(child_process.execFileSync("docker", ["inspect", ...containerIds], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
    }));
  } catch (error: any) {
    fail(`❌ Failed to inspect Pegas containers: ${error.message}`);
    return;
  }

  const found = new Set<string>();
  const problems: string[] = [];
  for (const container of containers) {
    const labels = container.Config?.Labels || {};
    const serviceName = labels["pegas.service"];
    if (!serviceName) continue;
    found.add(serviceName);

    const expectedHash = generated.serviceHashes[serviceName];
    if (!expectedHash) {
      problems.push(`${serviceName}: container is no longer declared in pegas.json`);
      continue;
    }
    if (labels["pegas.manifest-hash"] !== expectedHash) {
      problems.push(`${serviceName}: configuration drift detected; run 'pegas deploy development'`);
    }
    const expectedService = (generated.manifest.services as Record<string, { labels?: Record<string, string> }>)[serviceName];
    const expectedEnvHash = expectedService?.labels?.["pegas.env-hash"];
    if (expectedEnvHash && labels["pegas.env-hash"] !== expectedEnvHash) {
      problems.push(`${serviceName}: env file changed; run 'pegas deploy development'`);
    }
    if (container.State?.Status !== "running") {
      problems.push(`${serviceName}: container is ${container.State?.Status || "not running"}; run 'pegas deploy development'`);
    } else if (container.State?.Health && container.State.Health.Status !== "healthy") {
      problems.push(`${serviceName}: healthcheck is ${container.State.Health.Status}; run 'pegas deploy development'`);
    }
  }

  for (const serviceName of Object.keys(contract.services)) {
    if (!found.has(serviceName)) {
      problems.push(`${serviceName}: container is missing; run 'pegas deploy development'`);
    }
  }

  if (problems.length > 0) {
    fail("❌ Docker environment does not match pegas.json:\n" + problems.map((item) => `  - ${item}`).join("\n"));
    return;
  }

  let gatewayId = "";
  try {
    gatewayId = child_process.execFileSync("docker", [
      "ps", "-q", "--filter", "label=pegas.gateway=true",
    ], { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();
  } catch {}
  if (!gatewayId) {
    fail("❌ Shared Pegas Gateway is not running. Run 'pegas deploy development' to reconcile the environment.");
    return;
  }

  const urls = Object.values(contract.services)
    .flatMap((service) => getEnvironmentDomains(service, "development"))
    .map((domain) => `https://${domain}`);
  for (const url of urls) console.log(`🚀 Pegas development URL: ${url}`);

  console.log("📋 Attaching to existing Docker service logs. Press Ctrl+C to detach; containers will keep running.\n");
  await runRuntimeCompose(contract, projectRoot, projectId, ["logs", "--follow", "--tail", "100"], { ...process.env, PEGAS_ENV: "development", NODE_ENV: "development" });
}

export async function handleDev(options: DevOptions = {}): Promise<void> {
  const cwd = options.cwd || process.cwd();
  const projectRoot = (await findProjectRoot(cwd)) || cwd;

  // 1. Read pegas.json contract
  const contractPath = path.join(projectRoot, CONTRACT_FILENAME);
  let contractRaw: string;
  try {
    contractRaw = await fs.readFile(contractPath, "utf-8");
  } catch {
    console.error(`❌ Error: Contract '${CONTRACT_FILENAME}' not found in project root (${projectRoot}).`);
    console.error(`   Run 'pegas init' first to generate the contract.`);
    if (!options.noExit) {
      process.exit(1);
    }
    return;
  }

  let contract: PegasContract;
  try {
    contract = JSON.parse(contractRaw);
  } catch (err: any) {
    console.error(`❌ Error: Failed to parse '${path.basename(contractPath)}': Invalid JSON syntax.`);
    console.error(`   ${err.message}`);
    if (!options.noExit) {
      process.exit(1);
    }
    return;
  }

  if (contract.runtime === "docker") {
    await handleDockerRuntimeDev(contract, projectRoot, options);
    return;
  }

  // 2. Discover and boot infrastructure services (Postgres, Redis, Mongo, etc.)
  // Configured in pegas.json ("bootInfra") -> Default (false)
  const shouldBoot = Boolean(contract.bootInfra);

  let startedInfraServices: string[] = [];
  const composeFile = await findRootCompose(projectRoot);
  if (composeFile) {
    try {
      const composeContent = await fs.readFile(path.join(projectRoot, composeFile), "utf-8");
      const infraServices = detectInfraServices(composeContent);

      if (infraServices.length > 0) {
        if (shouldBoot) {
          console.log(`📦 Booting project infrastructure with Docker Compose...`);
          const serviceNames = infraServices.map((s) => s.name);

          try {
            child_process.execFileSync("docker", ["compose", "up", "-d", ...serviceNames], {
              cwd: projectRoot,
              stdio: "pipe",
            });
            startedInfraServices = serviceNames;

            for (const s of infraServices) {
              const port = s.hostPort || (s.containerPort ? String(s.containerPort) : "ready");
              console.log(`🟢 Infra [${s.name}] is ready on localhost:${port}`);
            }
            console.log("");
          } catch (err: any) {
            console.warn(`⚠️  Warning: Failed to auto-start infra services: ${err.message}\n`);
          }
        } else {
          const list = infraServices.map((s) => s.name).join(", ");
          console.log(`💡 Tip: Detected infra services (${list}). Set '"bootInfra": true' in ${CONTRACT_FILENAME} to auto-boot.\n`);
        }
      }
    } catch {}
  }

  // 3. Выбор портов: чистые URL на 443/80 при возможности, иначе откат на 8443/8080
  const preferredHttps = contract.devGateway?.httpsPort ?? DEFAULT_HTTPS_PORT;
  const preferredHttp = contract.devGateway?.httpPort ?? DEFAULT_HTTP_PORT;

  const caddyPath = await findOrDownloadCaddy({
    customPath: options.caddyPath || contract.devGateway?.caddyPath,
    useSystemCaddy: options.systemCaddy ?? contract.devGateway?.systemCaddy,
  });

  const lowPortsAllowed = canBindLowPorts(process.platform, null, caddyPath);

  /**
   * Зонд низких портов из Node-процесса ЛОЖНО возвращает EACCES, когда
   * Caddy имеет cap_net_bind_service (зондирует процесс без cap, а слушать
   * будет Caddy). Поэтому:
   * - низкий порт + cap на Caddy -> НЕ зондируем из Node вовсе: занятость
   *   порта поймает сам Caddy ошибкой bind, которую dev перехватывает ниже;
   * - низкий порт без cap -> честный fallback;
   * - высокий порт (>= 1024) -> обычный зонд, cap не нужен.
   */
  const caddyCanBindPreferredHttps = preferredHttps >= 1024 || (preferredHttps === DEFAULT_HTTPS_PORT && lowPortsAllowed);
  const caddyCanBindPreferredHttp = preferredHttp >= 1024 || (preferredHttp === DEFAULT_HTTP_PORT && lowPortsAllowed);

  let httpsPort: number;
  if (caddyCanBindPreferredHttps) {
    httpsPort = preferredHttps; // занятость порта проверит сам Caddy (у него права)
  } else if (preferredHttps >= 1024) {
    httpsPort = (await isPortAvailable(preferredHttps))
      ? preferredHttps
      : await findAvailablePort(FALLBACK_HTTPS_PORT);
  } else {
    httpsPort = await findAvailablePort(FALLBACK_HTTPS_PORT);
  }

  let httpPort: number;
  if (caddyCanBindPreferredHttp) {
    httpPort = preferredHttp;
  } else if (preferredHttp >= 1024) {
    httpPort = (await isPortAvailable(preferredHttp))
      ? preferredHttp
      : await findAvailablePort(FALLBACK_HTTP_PORT, [httpsPort]);
  } else {
    httpPort = await findAvailablePort(FALLBACK_HTTP_PORT, [httpsPort]);
  }

  // Низкие порты с cap считаются доступными до старта Caddy — fallback
  // определится только по факту ошибки bind (см. обработку caddyStderr).
  const fellBack = httpsPort !== preferredHttps || httpPort !== preferredHttp;

  // Статус CA нужен всегда (для Caddyfile): если не доверен — Caddy обязан
  // молчать про trust (sudo-промпт посреди dev недопустим).
  const caTrusted = await isCaTrusted();

  // Подсказка для рантаймов, которые не читают trust store ОС (Node/Bun/Python):
  // встроенный CA-лист вместо системного хранилища. NODE_EXTRA_CA_CERTS в env
  // дочернего процесса — чтобы fetch() из dev-сервера доверял локальному HTTPS.
  const nodeCaEnv: Record<string, string> =
    caTrusted ? { NODE_EXTRA_CA_CERTS: getCaPaths().caCertPath } : {};

  if (fellBack) {
    // Классифицируем причину fallback. EACCES из Node-зонда для низкого порта
    // без cap — это ожидаемое поведение Linux (не «порт занят»); настоящий
    // сценарий Windows-политики ловится только тогда, когда даже Caddy
    // с cap не смог забиндить порт (см. обработку caddyStderr ниже).
    if (!lowPortsAllowed && (preferredHttps < 1024 || preferredHttp < 1024)) {
      console.warn(
        `⚠️  Notice: Caddy lacks 'cap_net_bind_service', so ports ${preferredHttps}/${preferredHttp} are not bindable.\n` +
          `   Run 'pegas ca install' once to grant Caddy the capability (Linux) or use high ports.`
      );
    } else {
      console.warn(
        `⚠️  Notice: Ports ${preferredHttps}/${preferredHttp} are unavailable (busy or require permissions).` +
          ` Falling back to ports ${httpsPort}/${httpPort}.`
      );
    }
    if (!caTrusted) {
      console.warn(`💡 Tip: Run 'pegas ca install' to allow clean URLs on standard HTTPS port.`);
    }
  }

  // 5. Clean up any stale legacy Caddyfile.dev
  const devCaddyfilePath = path.join(projectRoot, ".pegas", "Caddyfile.dev");
  await fs.unlink(devCaddyfilePath).catch(() => {});

  // 6. Generate dev Caddyfile configuration in-memory
  const caddyfileContent = generateDevCaddyfile(contract, { httpsPort, httpPort }, { caTrusted });

  // 7. Start Caddy in background child process piping config via stdin
  console.log("🔒 Starting local Caddy HTTPS proxy...");
  const caddyProc: ChildProcess = child_process.spawn(
    caddyPath,
    ["run", "--adapter", "caddyfile", "--config", "-"],
    {
      stdio: ["pipe", "pipe", "pipe"],
      cwd: projectRoot,
      env: { ...process.env, ...getCaddyHomeEnv() },
    }
  );

  if (caddyProc.stdin) {
    caddyProc.stdin.on("error", () => {});
    caddyProc.stdin.write(caddyfileContent);
    caddyProc.stdin.end();
  }

  let caddyStderr = "";
  caddyProc.stderr?.on("data", (chunk) => {
    const text = chunk.toString();
    caddyStderr += text;
    if (text.includes("bind: address already in use") || text.includes("permission denied")) {
      console.error(`\n❌ Caddy error: ${text.trim()}`);
      // Диагностика Windows-политики: даже cap не помогла — порт исключён ОС
      // (типично для WSL в mirrored-режиме).
      if (text.includes("permission denied") && process.platform === "linux") {
        console.error(
          `   Port is blocked by the OS policy. On WSL (mirrored networking) check excluded ranges:\n` +
            `   'netsh interface ipv4 show excludedportrange protocol=tcp' in Windows PowerShell.`
        );
      }
    }
  });

  // Check if Caddy crashed immediately (e.g. port conflict or invalid config)
  await new Promise((resolve) => setTimeout(resolve, 300));
  if (caddyProc.exitCode !== null) {
    console.error("❌ Failed to start Caddy proxy:");
    console.error(caddyStderr);
    if (!options.noExit) {
      process.exit(1);
    }
    return;
  }

  // Collect configured dev domains for display (standard port -> clean URL)
  const isStandardHttps = httpsPort === 443;
  const isStandardHttp = httpPort === 80;
  const devUrls: string[] = [];
  for (const s of Object.values(contract.services || {})) {
    for (const d of getEnvironmentDomains(s, "development")) {
      devUrls.push(isStandardHttps ? `https://${d}` : `https://${d}:${httpsPort}`);
    }
  }
  if (devUrls.length === 0) {
    devUrls.push(isStandardHttps ? "https://app.localhost" : `https://app.localhost:${httpsPort}`);
  }

  for (const u of devUrls) {
    console.log(`🚀 Pegas proxy active at: ${u}`);
  }

  // 7. Start developer command if specified
  let userProc: ChildProcess | null = null;
  const userCmdArgs = options.command || [];
  const isWin = process.platform === "win32";

  let isCleaningUp = false;
  function cleanup(exitCode = 0) {
    if (isCleaningUp) return;
    isCleaningUp = true;

    if (caddyProc && !caddyProc.killed) {
      try {
        caddyProc.kill("SIGTERM");
      } catch {}
    }

    if (userProc && !userProc.killed && userProc.pid) {
      try {
        if (isWin) {
          userProc.kill("SIGTERM");
        } else {
          // Kill the entire process group to avoid orphaned child processes
          process.kill(-userProc.pid, "SIGTERM");
        }
      } catch {}
    }

    if (startedInfraServices.length > 0) {
      try {
        console.log(`\n🛑 Stopping infrastructure services: ${startedInfraServices.join(", ")}...`);
        child_process.execFileSync("docker", ["compose", "stop", ...startedInfraServices], {
          cwd: projectRoot,
          stdio: "pipe",
        });
      } catch {}
    }

    if (!options.noExit) {
      process.exit(exitCode);
    }
  }

  process.on("SIGINT", () => cleanup(0));
  process.on("SIGTERM", () => cleanup(0));

  caddyProc.on("exit", (code) => {
    if (!isCleaningUp) {
      console.log(`\n⚠️  Caddy proxy exited with code ${code}`);
      cleanup(code || 0);
    }
  });

  if (userCmdArgs.length > 0) {
    const cmdBinary = userCmdArgs[0];
    const cmdArgs = userCmdArgs.slice(1);
    const cmdStr = userCmdArgs.join(" ");
    console.log(`📦 Running command: ${cmdStr}\n`);

    let primaryDevDomain = "";
    for (const sCfg of Object.values(contract.services || {})) {
      const dList = getEnvironmentDomains(sCfg, "development");
      if (dList.length > 0) {
        primaryDevDomain = dList[0];
        break;
      }
    }

    const localBinPath = path.join(projectRoot, "node_modules", ".bin");
    const devEnv = {
      ...process.env,
      PATH: `${localBinPath}:${process.env.PATH || ""}`,
      NODE_ENV: "development",
      PEGAS_ENV: "development",
      ...nodeCaEnv,
      ...(primaryDevDomain ? { APP_DOMAIN: primaryDevDomain } : {}),
    };

    await new Promise<void>((resolve) => {
      userProc = child_process.spawn(cmdBinary, cmdArgs, {
        shell: isWin,
        stdio: "inherit",
        cwd: projectRoot,
        detached: !isWin,
        env: devEnv,
      });

      userProc.on("exit", (code) => {
        cleanup(code || 0);
        resolve();
      });

      userProc.on("error", (err) => {
        console.error(`❌ Failed to start command '${cmdStr}':`, err.message);
        cleanup(1);
        resolve();
      });
    });
  } else {
    console.log("💡 Caddy proxy running in foreground. Press Ctrl+C to stop.");
    await new Promise(() => {});
  }
}
