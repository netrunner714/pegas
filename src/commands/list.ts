import fs from "node:fs/promises";
import path from "node:path";
import { findGatewayDir } from "../gateway.js";
import { runCommand } from "../docker.js";
import { renderTable } from "../table.js";

export interface DockerContainerInfo {
  id: string;
  name: string;
  image: string;
  state: string;
  status: string;
  networks: string[];
  composeProject?: string;
  composeService?: string;
}

export interface ParsedProjectRoute {
  projectName: string;
  domains: string[];
  upstream: string;
  filePath: string;
}

export interface ProjectDashboardItem {
  project: string;
  domains: string[];
  upstream: string;
  status: string;
  state: string;
  displayStatus: string;
  container?: string;
  containerId?: string;
}

/**
 * Parses a project's Caddy configuration file (e.g. conf.d/<project>.caddy).
 * Extracts project name, routed domains, and upstream reverse_proxy targets.
 */
export function parseCaddyProjectFile(content: string, filename: string): ParsedProjectRoute[] {
  // 1. Extract project name from header comment or filename
  let projectName = path.basename(filename, ".caddy");
  const projectCommentMatch = content.match(/#\s*Auto-generated by Pegas for project:\s*([^\n\r]+)/i);
  if (projectCommentMatch && projectCommentMatch[1]) {
    projectName = projectCommentMatch[1].trim();
  }

  const routes: ParsedProjectRoute[] = [];

  // 2. Discover www redirects (e.g. www.domain.com { redir https://domain.com... })
  const wwwRedirects = new Set<string>();
  const redirMatches = content.matchAll(/^([^{\n]+)\s*\{[^{}]*?redir\s+https?:\/\/([^\s\n{/]+)/gm);
  for (const rm of redirMatches) {
    const fromDomain = rm[1].trim();
    if (fromDomain.startsWith("www.")) {
      wwwRedirects.add(fromDomain);
    }
  }

  // 3. Extract site blocks with reverse_proxy
  // Matches site blocks:
  // domain.com { ... reverse_proxy app:3000 ... }
  // domain.com, api.domain.com { ... reverse_proxy app:3000 ... }
  const blockRegex = /^([^{\n]+)\s*\{([\s\S]*?)^\}/gm;
  let blockMatch: RegExpExecArray | null;

  while ((blockMatch = blockRegex.exec(content)) !== null) {
    const header = blockMatch[1].trim();
    const body = blockMatch[2];

    if (!header || header.startsWith("#")) continue;

    const proxyMatches = [...body.matchAll(/reverse_proxy\s+([^\s\n{}]+)/g)];
    if (proxyMatches.length === 0) {
      continue;
    }

    const upstream = proxyMatches[0][1];

    const rawDomains = header
      .split(",")
      .map((d) => d.trim())
      .filter((d) => d && !d.startsWith("#"));

    const domains: string[] = [];
    for (const d of rawDomains) {
      const clean = d.replace(/:\d+$/, "");
      if (!domains.includes(clean)) {
        domains.push(clean);
      }
      const wwwVariant = `www.${clean}`;
      if (wwwRedirects.has(wwwVariant) && !domains.includes(wwwVariant)) {
        domains.push(wwwVariant);
      }
    }

    if (domains.length > 0) {
      routes.push({
        projectName,
        domains,
        upstream,
        filePath: filename,
      });
    }
  }

  // Fallback: If no block matched but file contains reverse_proxy
  if (routes.length === 0) {
    const proxyMatch = content.match(/reverse_proxy\s+([^\s\n{}]+)/);
    if (proxyMatch) {
      routes.push({
        projectName,
        domains: [projectName],
        upstream: proxyMatch[1],
        filePath: filename,
      });
    }
  }

  return routes;
}

/**
 * Matches an upstream target with a running or stopped Docker container.
 */
export function matchContainerForRoute(
  upstream: string,
  projectName: string,
  containers: DockerContainerInfo[]
): DockerContainerInfo | null {
  const parts = upstream.split(":");
  const upstreamHost = parts[0];

  // 1. Exact container name match (ignoring leading slash)
  for (const c of containers) {
    const cleanName = c.name.replace(/^\//, "");
    if (cleanName === upstreamHost) {
      return c;
    }
  }

  // 2. Container name contains upstreamHost (e.g. "cool-app-web-1" contains "cool-app-web")
  for (const c of containers) {
    const cleanName = c.name.replace(/^\//, "");
    if (cleanName.startsWith(`${upstreamHost}-`) || cleanName.includes(upstreamHost)) {
      return c;
    }
  }

  // 3. Match by Compose project and service label
  let serviceName = upstreamHost;
  if (upstreamHost.startsWith(`${projectName}-`)) {
    serviceName = upstreamHost.slice(projectName.length + 1);
  }

  for (const c of containers) {
    if (c.composeProject === projectName && c.composeService === serviceName) {
      return c;
    }
  }

  // 4. Any container belonging to this compose project
  for (const c of containers) {
    if (c.composeProject === projectName) {
      return c;
    }
  }

  // 5. Container name starts with projectName
  for (const c of containers) {
    const cleanName = c.name.replace(/^\//, "");
    if (cleanName.startsWith(`${projectName}-`) || cleanName.startsWith(projectName)) {
      return c;
    }
  }

  return null;
}

export function formatDockerStatus(container: DockerContainerInfo | null): {
  displayStatus: string;
  state: string;
  statusText: string;
} {
  if (!container) {
    return {
      displayStatus: "\x1b[31m🔴 Offline\x1b[0m",
      state: "offline",
      statusText: "Offline",
    };
  }

  const state = container.state.toLowerCase();
  const rawStatus = container.status || state;

  if (state === "running") {
    const text = rawStatus.startsWith("Up") ? rawStatus : "Up";
    return {
      displayStatus: `\x1b[32m🟢 ${text}\x1b[0m`,
      state: "running",
      statusText: text,
    };
  }

  if (state === "restarting") {
    return {
      displayStatus: `\x1b[33m🟡 ${rawStatus}\x1b[0m`,
      state: "restarting",
      statusText: rawStatus,
    };
  }

  return {
    displayStatus: `\x1b[31m🔴 ${rawStatus || "Offline"}\x1b[0m`,
    state: state || "exited",
    statusText: rawStatus || "Offline",
  };
}

export async function getDockerContainers(): Promise<DockerContainerInfo[]> {
  try {
    const res = await runCommand("docker", ["ps", "-a", "--format", "{{json .}}"]);
    if (!res.success || !res.stdout.trim()) {
      return [];
    }

    const lines = res.stdout.trim().split("\n");
    const containers: DockerContainerInfo[] = [];

    for (const line of lines) {
      try {
        const item = JSON.parse(line.trim());
        const labels = item.Labels || "";
        const projectMatch = labels.match(/com\.docker\.compose\.project=([^,]+)/);
        const serviceMatch = labels.match(/com\.docker\.compose\.service=([^,]+)/);

        containers.push({
          id: item.ID || "",
          name: item.Names || "",
          image: item.Image || "",
          state: (item.State || "").toLowerCase(),
          status: item.Status || "",
          networks: (item.Networks || "").split(",").map((n: string) => n.trim()),
          composeProject: projectMatch ? projectMatch[1] : undefined,
          composeService: serviceMatch ? serviceMatch[1] : undefined,
        });
      } catch {}
    }

    return containers;
  } catch {
    return [];
  }
}

export async function handleList(options: { gatewayDir?: string; json?: boolean }): Promise<void> {
  const isJson = options.json ?? false;
  const gatewayDir = await findGatewayDir(options.gatewayDir);
  const confDir = path.join(gatewayDir, "conf.d");

  // 1. Read all .caddy files in gateway conf.d/
  const routes: ParsedProjectRoute[] = [];
  try {
    const files = await fs.readdir(confDir);
    for (const file of files) {
      if (!file.endsWith(".caddy")) continue;
      const filePath = path.join(confDir, file);
      try {
        const content = await fs.readFile(filePath, "utf-8");
        const parsed = parseCaddyProjectFile(content, file);
        routes.push(...parsed);
      } catch {}
    }
  } catch (err: any) {
    if (err.code !== "ENOENT") {
      throw err;
    }
  }

  if (routes.length === 0) {
    if (isJson) {
      console.log(JSON.stringify([], null, 2));
      return;
    }
    console.log("\nℹ️  No projects currently deployed to Pegas gateway.");
    console.log("   Run 'pegas deploy' inside a project directory to launch your first service.\n");
    return;
  }

  // 2. Fetch Docker container states
  const containers = await getDockerContainers();

  // 3. Assemble Dashboard items
  const items: ProjectDashboardItem[] = routes.map((route) => {
    const matchedContainer = matchContainerForRoute(route.upstream, route.projectName, containers);
    const { displayStatus, state, statusText } = formatDockerStatus(matchedContainer);

    return {
      project: route.projectName,
      domains: route.domains,
      upstream: route.upstream,
      status: statusText,
      state,
      displayStatus,
      container: matchedContainer ? matchedContainer.name.replace(/^\//, "") : undefined,
      containerId: matchedContainer?.id,
    };
  });

  // Sort by project name
  items.sort((a, b) => a.project.localeCompare(b.project));

  // 4. Output
  if (isJson) {
    // Strip displayStatus (with ANSI colors) from JSON output
    const cleanJson = items.map(({ displayStatus, ...rest }) => rest);
    console.log(JSON.stringify(cleanJson, null, 2));
    return;
  }

  console.log(`\n🚀 \x1b[1mPegas Global Dashboard\x1b[0m — Active Projects in ${gatewayDir}:\n`);

  const headers = ["PROJECT", "DOMAINS", "UPSTREAM", "STATUS"];
  const rows = items.map((item) => [
    item.project,
    item.domains.join(", "),
    item.upstream,
    item.displayStatus,
  ]);

  console.log(renderTable({ headers, rows }));
  console.log(`\nTotal: ${items.length} active route${items.length === 1 ? "" : "s"}\n`);
}
