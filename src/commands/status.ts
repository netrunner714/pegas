export function parseCaddyTopLevelBlocks(content: string): Array<{ header: string; body: string }> {
  const blocks: Array<{ header: string; body: string }> = [];
  let i = 0;
  const n = content.length;

  while (i < n) {
    const openBrace = content.indexOf("{", i);
    if (openBrace === -1) break;

    const beforeText = content.slice(i, openBrace).trim();
    const lines = beforeText.split("\n").map((l) => l.trim()).filter((l) => Boolean(l) && !l.startsWith("#"));
    const header = lines[lines.length - 1] || "";

    let depth = 1;
    let j = openBrace + 1;
    let inQuote = false;
    let quoteChar = "";

    while (j < n && depth > 0) {
      const char = content[j];
      if (inQuote) {
        if (char === quoteChar && content[j - 1] !== "\\") {
          inQuote = false;
        }
      } else if (char === '"' || char === "'") {
        inQuote = true;
        quoteChar = char;
      } else if (char === "{") {
        depth++;
      } else if (char === "}") {
        depth--;
      }
      j++;
    }

    if (depth === 0) {
      const body = content.slice(openBrace + 1, j - 1);
      if (header && !header.startsWith("#")) {
        blocks.push({ header, body });
      }
      i = j;
    } else {
      break;
    }
  }

  return blocks;
}

export function parseCaddyProjectFile(content: string, filename: string): ParsedProjectRoute[] {
  let projectName = path.basename(filename, ".caddy");
  const projectCommentMatch = content.match(/#\s*Auto-generated by Pegas for project:\s*([^\n\r\[]+)/i);
  if (projectCommentMatch && projectCommentMatch[1]) {
    projectName = projectCommentMatch[1].trim();
  } else {
    const envSuffixMatch = projectName.match(/^(.+?)-(stage|prod|production|dev|development)$/i);
    if (envSuffixMatch) {
      projectName = envSuffixMatch[1];
    }
  }

  const routes: ParsedProjectRoute[] = [];
  const topBlocks = parseCaddyTopLevelBlocks(content);

  const wwwRedirects = new Set<string>();
  for (const block of topBlocks) {
    if (block.body.includes("redir ") && block.header.startsWith("www.")) {
      wwwRedirects.add(block.header);
    }
  }

  for (const block of topBlocks) {
    const header = block.header;
    const body = block.body;

    if (body.includes("redir https://")) {
      continue;
    }

    const domainList = header
      .split(/[\s,]+/)
      .map((d) => d.trim())
      .filter((d) => Boolean(d) && !d.startsWith("#"));

    const proxyMatches = body.matchAll(/reverse_proxy\s+([^\s\n{}]+)/g);
    for (const pm of proxyMatches) {
      const upstream = pm[1].trim();
      const allDomains = [...domainList];
      for (const d of domainList) {
        const wwwVariant = `www.${d}`;
        if (wwwRedirects.has(wwwVariant) && !allDomains.includes(wwwVariant)) {
          allDomains.push(wwwVariant);
        }
      }

      routes.push({
        projectName,
        domains: allDomains,
        upstream,
        filePath: filename,
      });
    }
  }

  return routes;
}

export function matchContainerForRoute(
  upstream: string,
  projectName: string,
  containers: DockerContainerInfo[]
): DockerContainerInfo | undefined {
  const hostPart = upstream.split(":")[0];

  if (hostPart === "host.docker.internal" || hostPart === "127.0.0.1" || hostPart === "localhost") {
    return undefined;
  }

  const composeMatch = containers.find(
    (c) =>
      c.composeProject?.toLowerCase() === projectName.toLowerCase() &&
      c.composeService?.toLowerCase() === hostPart.toLowerCase()
  );
  if (composeMatch) return composeMatch;

  const exactNameMatch = containers.find((c) => {
    const cleanName = c.name.replace(/^\//, "");
    return cleanName === hostPart;
  });
  if (exactNameMatch) return exactNameMatch;

  const prefixMatch = containers.find((c) => {
    const cleanName = c.name.replace(/^\//, "");
    return cleanName.startsWith(`${projectName}_`) || cleanName.startsWith(`${projectName}-`);
  });
  if (prefixMatch) return prefixMatch;

  return undefined;
}

export function formatDockerStatus(container?: DockerContainerInfo, upstream?: string): {
  displayStatus: string;
  state: string;
  statusText: string;
} {
  if (!container) {
    if (
      upstream?.startsWith("host.docker.internal") ||
      upstream?.startsWith("127.0.0.1") ||
      upstream?.startsWith("localhost")
    ) {
      return {
        displayStatus: "\x1b[36m💻 Host (dev)\x1b[0m",
        state: "host",
        statusText: "Host (dev)",
      };
    }
    return {
      displayStatus: "\x1b[90m⚪ Not started\x1b[0m",
      state: "stopped",
      statusText: "Not started",
    };
  }

  const state = container.state?.toLowerCase();
  const rawStatus = container.status || "";

  if (state === "running") {
    const isHealthy = rawStatus.toLowerCase().includes("(healthy)");
    const isUnhealthy = rawStatus.toLowerCase().includes("(unhealthy)");
    const isStarting = rawStatus.toLowerCase().includes("(health: starting)");

    if (isHealthy) {
      return {
        displayStatus: "\x1b[32m🟢 Up (healthy)\x1b[0m",
        state: "running",
        statusText: "Up (healthy)",
      };
    }
    if (isUnhealthy) {
      return {
        displayStatus: "\x1b[31m🔴 Up (unhealthy)\x1b[0m",
        state: "running",
        statusText: "Up (unhealthy)",
      };
    }
    if (isStarting) {
      return {
        displayStatus: "\x1b[33m🟡 Up (starting)\x1b[0m",
        state: "running",
        statusText: "Up (starting)",
      };
    }

    const text = rawStatus ? `Up (${rawStatus.replace(/^Up\s+/i, "")})` : "Up";
    return {
      displayStatus: `\x1b[32m🟢 ${text}\x1b[0m`,
      state: "running",
      statusText: text,
    };
  }

  if (state === "restarting") {
    return {
      displayStatus: `\x1b[33m🟡 ${rawStatus}\x1b[0m`,
      state: "restarting",
      statusText: rawStatus,
    };
  }

  return {
    displayStatus: `\x1b[31m🔴 ${rawStatus || "Offline"}\x1b[0m`,
    state: state || "exited",
    statusText: rawStatus || "Offline",
  };
}

export async function getDockerContainers(): Promise<DockerContainerInfo[]> {
  try {
    const res = await runCommand("docker", ["ps", "-a", "--format", "{{json .}}"]);
    if (!res.success || !res.stdout.trim()) {
      return [];
    }

    const lines = res.stdout.trim().split("\n");
    const containers: DockerContainerInfo[] = [];

    for (const line of lines) {
      try {
        const item = JSON.parse(line.trim());
        const labels = item.Labels || "";
        const projectMatch = labels.match(/com\.docker\.compose\.project=([^,]+)/);
        const serviceMatch = labels.match(/com\.docker\.compose\.service=([^,]+)/);
        const pegasProjectMatch = labels.match(/pegas\.project-name=([^,]+)/);
        const pegasServiceMatch = labels.match(/pegas\.service=([^,]+)/);
        const pegasRoleMatch = labels.match(/pegas\.role=([^,]+)/);
        const pegasDomainsMatch = labels.match(/pegas\.domains=([^,]+)/);
        const pegasEndpointMatch = labels.match(/pegas\.endpoint=([^,]+)/);

        containers.push({
          id: item.ID || "",
          name: item.Names || "",
          image: item.Image || "",
          state: (item.State || "").toLowerCase(),
          status: item.Status || "",
          networks: (item.Networks || "").split(",").map((n: string) => n.trim()),
          ports: item.Ports || "",
          composeProject: projectMatch ? projectMatch[1] : undefined,
          composeService: serviceMatch ? serviceMatch[1] : undefined,
          pegasProject: pegasProjectMatch ? pegasProjectMatch[1] : undefined,
          pegasService: pegasServiceMatch ? pegasServiceMatch[1] : undefined,
          pegasRole: pegasRoleMatch ? pegasRoleMatch[1] : undefined,
          pegasDomains: pegasDomainsMatch ? pegasDomainsMatch[1] : undefined,
          pegasEndpoint: pegasEndpointMatch ? pegasEndpointMatch[1] : undefined,
        });
      } catch {}
    }

    return containers;
  } catch {
    return [];
  }
}

export function resolveInfraEndpoint(
  c: DockerContainerInfo,
  proj: string,
  svc: string,
  cleanPorts: string
): string {
  if (c.pegasEndpoint) return c.pegasEndpoint;
  const hostPort = cleanPorts && cleanPorts !== "-" ? cleanPorts.split("->")[0].trim() : "";
  if (c.pegasDomains) {
    const firstDomain = c.pegasDomains.split(",")[0].trim();
    return hostPort ? `${firstDomain}:${hostPort}` : firstDomain;
  }
  const candidates = [
    path.join(process.cwd(), "pegas.json"),
    path.join(process.cwd(), proj, "pegas.json"),
    path.join(path.dirname(process.cwd()), proj, "pegas.json"),
    path.join("/home/vibe", proj, "pegas.json"),
  ];
  for (const cPath of candidates) {
    try {
      if (fsSync.existsSync(cPath)) {
        const raw = fsSync.readFileSync(cPath, "utf-8");
        const contract = JSON.parse(raw);
        if (contract.projectName === proj) {
          const svcConf = contract.services?.[svc];
          const dList = svcConf?.domains?.development || svcConf?.domains;
          if (Array.isArray(dList) && dList[0]) {
            return hostPort ? `${dList[0]}:${hostPort}` : dList[0];
          }
          if (contract.env?.PUBLIC_HOST) {
            const pub =
              typeof contract.env.PUBLIC_HOST === "object"
                ? contract.env.PUBLIC_HOST.development
                : contract.env.PUBLIC_HOST;
            if (pub) {
              const resolvedPub = interpolateServiceReferences(pub, contract, "development");
              return hostPort ? `${resolvedPub}:${hostPort}` : resolvedPub;
            }
          }
        }
      }
    } catch {}
  }
  if (hostPort) {
    return `${svc}.${proj}.localhost:${hostPort}`;
  }
  return "-";
}

export async function handleStatus(options: { gatewayDir?: string; json?: boolean }): Promise<void> {
  const isJson = options.json ?? false;

  const dockerOk = await checkDocker();
  const composeOk = await checkDockerCompose();
  const gatewayDir = await findGatewayDir(options.gatewayDir);

  const netInspect = await runCommand("docker", ["network", "inspect", "pegas-network"]);
  const networkOk = netInspect.success;

  const containerStatus = await getGatewayContainerStatus(gatewayDir);
  const isRunning = containerStatus.success && containerStatus.stdout.includes("caddy");

  const confDir = path.join(gatewayDir, "conf.d");
  const routes: ParsedProjectRoute[] = [];
  try {
    const files = await fs.readdir(confDir);
    for (const file of files) {
      if (!file.endsWith(".caddy")) continue;
      const filePath = path.join(confDir, file);
      try {
        const content = await fs.readFile(filePath, "utf-8");
        const parsed = parseCaddyProjectFile(content, file);
        routes.push(...parsed);
      } catch {}
    }
  } catch (err: any) {
    if (err.code !== "ENOENT") {
      throw err;
    }
  }

  const containers = await getDockerContainers();
  const items: ProjectDashboardItem[] = routes.map((route) => {
    const matchedContainer = matchContainerForRoute(route.upstream, route.projectName, containers);
    const { displayStatus, state, statusText } = formatDockerStatus(matchedContainer, route.upstream);

    return {
      project: route.projectName,
      domains: route.domains,
      upstream: route.upstream,
      status: statusText,
      state,
      displayStatus,
      container: matchedContainer ? matchedContainer.name.replace(/^\//, "") : undefined,
      containerId: matchedContainer?.id,
    };
  });

  items.sort((a, b) => a.project.localeCompare(b.project));

  const matchedContainerIds = new Set(items.map((i) => i.containerId).filter(Boolean));
  const infraContainers = containers.filter((c) => {
    if (c.name === "pegas-gateway" || c.name === "/pegas-gateway") return false;
    if (matchedContainerIds.has(c.id)) return false;
    return Boolean(c.pegasProject || c.composeProject) && c.state === "running";
  });

  if (isJson) {
    const cleanProjects = items.map(({ displayStatus, ...rest }) => rest);
    const cleanInfra = infraContainers.map((c) => {
      const proj =
        c.pegasProject ||
        c.composeProject?.replace(/-[a-f0-9]{12}-development|-development|-production|-stage/g, "") ||
        "unknown";
      const svc = c.pegasService || c.composeService || c.name.replace(/^\//, "");
      const { statusText } = formatDockerStatus(c);
      const cleanPorts = c.ports
        ? c.ports
            .split(",")
            .map((p) => p.trim().replace(/0\.0\.0\.0:|\[::\]:/g, "").replace(/\/tcp|\/udp/g, ""))
            .filter(Boolean)
            .filter((v, i, a) => a.indexOf(v) === i)
            .join(", ")
        : "-";
      const endpoint = resolveInfraEndpoint(c, proj, svc, cleanPorts);
      return {
        project: proj,
        service: svc,
        endpoint,
        image: c.image,
        ports: c.ports,
        status: statusText,
        state: c.state,
        containerId: c.id,
        containerName: c.name.replace(/^\//, ""),
      };
    });
    console.log(
      JSON.stringify(
        {
          docker: dockerOk,
          compose: composeOk,
          network: { name: "pegas-network", exists: networkOk },
          gatewayDir,
          activeRoutesCount: routes.length,
          gateway: {
            docker: dockerOk,
            compose: composeOk,
            network: { name: "pegas-network", exists: networkOk },
            container: { running: isRunning, details: containerStatus.stdout },
            gatewayDir,
            activeRoutesCount: routes.length,
          },
          projects: cleanProjects,
          infrastructure: cleanInfra,
        },
        null,
        2
      )
    );
    return;
  }

  console.log("\n📡 \x1b[1mPegas Gateway Status:\x1b[0m\n");
  console.log(`  Docker Engine:      ${dockerOk ? "✓ Active" : "✗ Offline"}`);
  console.log(`  Docker Compose:     ${composeOk ? "✓ Available" : "✗ Missing"}`);
  console.log(`  Docker Network:     ${networkOk ? "✓ 'pegas-network' exists" : "✗ 'pegas-network' missing"}`);
  console.log(`  Caddy Container:    ${isRunning ? "✓ Running" : "✗ Stopped or not found"}`);
  console.log(`  Gateway Location:   ${gatewayDir}`);
  console.log(`  Active Routes:      ${routes.length} domain(s)\n`);

  if (items.length > 0) {
    console.log(`🚀 \x1b[1mActive Web Routes (HTTP/HTTPS):\x1b[0m\n`);
    const headers = ["PROJECT", "DOMAINS", "UPSTREAM", "STATUS"];
    const rows = items.map((item) => [
      item.project,
      item.domains.join(", "),
      item.upstream,
      item.displayStatus,
    ]);
    console.log(renderTable({ headers, rows }));
    console.log(`\nTotal: ${items.length} active route${items.length === 1 ? "" : "s"}\n`);
  } else {
    console.log("ℹ️  No web routes currently deployed to Pegas gateway.\n");
  }

  if (infraContainers.length > 0) {
    console.log(`📦 \x1b[1mActive Infrastructure & Background Services:\x1b[0m\n`);
    const infraHeaders = ["PROJECT", "SERVICE", "ENDPOINT / HOST", "IMAGE", "PORTS", "STATUS"];
    const infraRows = infraContainers.map((c) => {
      const proj =
        c.pegasProject ||
        c.composeProject?.replace(/-[a-f0-9]{12}-development|-development|-production|-stage/g, "") ||
        "unknown";
      const svc = c.pegasService || c.composeService || c.name.replace(/^\//, "");
      const { displayStatus } = formatDockerStatus(c);
      const cleanPorts = c.ports
        ? c.ports
            .split(",")
            .map((p) => p.trim().replace(/0\.0\.0\.0:|\[::\]:/g, "").replace(/\/tcp|\/udp/g, ""))
            .filter(Boolean)
            .filter((v, i, a) => a.indexOf(v) === i)
            .join(", ")
        : "-";
      const endpoint = resolveInfraEndpoint(c, proj, svc, cleanPorts);
      return [proj, svc, endpoint, c.image, cleanPorts || "-", displayStatus];
    });
    console.log(renderTable({ headers: infraHeaders, rows: infraRows }));
    console.log(`\nTotal: ${infraContainers.length} active service${infraContainers.length === 1 ? "" : "s"}\n`);
  }
}
