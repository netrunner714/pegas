import { describe, it, expect } from "bun:test";
import {
  serializeRouteMeta,
  parseRouteMeta,
  inferRouteMeta,
  ROUTE_META_PREFIX,
  type RouteMeta,
} from "./route-meta.js";

describe("route-meta: сериализация (issue #30)", () => {
  const meta: RouteMeta = {
    project: "815records",
    service: "booking-api",
    env: "development",
    driver: "bun",
    owner: "connect",
    port: 3002,
  };

  it("строит однострочный комментарий с маркером # pegas:", () => {
    const line = serializeRouteMeta(meta)!;
    expect(line.startsWith(ROUTE_META_PREFIX)).toBe(true);
    expect(line.startsWith("# pegas:")).toBe(true);
    expect(line).toBe(
      "# pegas:project=815records | service=booking-api | env=development | driver=bun | owner=connect | port=3002"
    );
  });

  it("не содержит переводов строк: комментарий обязан остаться одной строкой", () => {
    expect(serializeRouteMeta(meta)).not.toContain("\n");
  });

  it("порядок ключей стабилен — diff route-файлов не шумит", () => {
    const reordered: RouteMeta = { port: 3002, owner: "connect", driver: "bun", env: "development", service: "booking-api", project: "815records" };
    expect(serializeRouteMeta(reordered)).toBe(serializeRouteMeta(meta));
  });

  it("необязательные ключи пропускаются, обязательные всегда на месте", () => {
    const line = serializeRouteMeta({ project: "p", service: "s", env: "production", driver: "docker" })!;
    expect(line).toBe("# pegas:project=p | service=s | env=production | driver=docker");
    expect(line).not.toContain("owner");
    expect(line).not.toContain("port");
  });

  it("неполные метаданные не сериализуются (null, а не мусорная строка)", () => {
    expect(serializeRouteMeta({ project: "", service: "s", env: "dev", driver: "docker" } as RouteMeta)).toBeNull();
    expect(serializeRouteMeta({ project: "p", service: "s", env: "", driver: "docker" } as RouteMeta)).toBeNull();
  });

  it("значение вне алфавита имён в обязательном поле → null: строка не помогла бы сопоставить сервис", () => {
    expect(serializeRouteMeta({ ...meta, service: "bad service|name" } as RouteMeta)).toBeNull();
    expect(serializeRouteMeta({ ...meta, project: "proj|ect" } as RouteMeta)).toBeNull();
  });

  it("значение вне алфавита в необязательном поле отбрасывается, обязательные сохраняются", () => {
    const line = serializeRouteMeta({ project: "p", service: "s", env: "dev", driver: "docker", owner: "bad|owner" as never })!;
    expect(line).toBe("# pegas:project=p | service=s | env=dev | driver=docker");
    expect(line).not.toContain("owner");
  });
});

describe("route-meta: разбор (issue #30)", () => {
  it("round-trip: сериализация → разбор без потерь", () => {
    const meta: RouteMeta = { project: "myapp", service: "api", env: "production", driver: "docker", owner: "deploy", port: 8000 };
    expect(parseRouteMeta(serializeRouteMeta(meta))).toEqual(meta);
  });

  it("round-trip без необязательных полей", () => {
    const meta: RouteMeta = { project: "myapp", service: "web", env: "development", driver: "bun" };
    expect(parseRouteMeta(serializeRouteMeta(meta))).toEqual(meta);
  });

  it("принимает массив комментариев блока и берёт строку метаданных", () => {
    const meta: RouteMeta = { project: "myapp", service: "web", env: "development", driver: "bun" };
    const parsed = parseRouteMeta(["# Auto-generated by Pegas for project: myapp [development]", serializeRouteMeta(meta)!]);
    expect(parsed).toEqual(meta);
  });

  it("неизвестные ключи игнорируются: рукописные правки не ломают разбор", () => {
    const parsed = parseRouteMeta("# pegas:project=p | service=s | env=dev | driver=docker | future-key=x");
    expect(parsed).toEqual({ project: "p", service: "s", env: "dev", driver: "docker" });
  });

  it("отсутствие маркера / пустой ввод → null", () => {
    expect(parseRouteMeta("# обычный комментарий")).toBeNull();
    expect(parseRouteMeta([])).toBeNull();
    expect(parseRouteMeta(null)).toBeNull();
    expect(parseRouteMeta(undefined)).toBeNull();
  });

  it("строка без обязательных полей → null (не частичные метаданные)", () => {
    expect(parseRouteMeta("# pegas:service=s | env=dev")).toBeNull();
    expect(parseRouteMeta("# pegas:")).toBeNull();
  });

  it("нечитаемый driver трактуется как docker — значение по умолчанию контракта", () => {
    expect(parseRouteMeta("# pegas:project=p | service=s | env=dev | driver=weird")?.driver).toBe("docker");
    expect(parseRouteMeta("# pegas:project=p | service=s | env=dev | driver=bun")?.driver).toBe("bun");
  });

  it("нечисловой или неположительный port не попадает в результат", () => {
    expect(parseRouteMeta("# pegas:project=p | service=s | env=dev | driver=bun | port=abc")).toEqual({
      project: "p", service: "s", env: "dev", driver: "bun",
    });
    expect(parseRouteMeta("# pegas:project=p | service=s | env=dev | driver=bun | port=0")?.port).toBeUndefined();
  });

  it("регистр ключей не важен", () => {
    expect(parseRouteMeta("# pegas:Project=p | SERVICE=s | Env=dev | Driver=bun")).toEqual({
      project: "p", service: "s", env: "dev", driver: "bun",
    });
  });
});

describe("route-meta: вывод из upstream (обратная совместимость)", () => {
  it("host.docker.internal → driver bun, owner connect (правило #23)", () => {
    const inferred = inferRouteMeta({ projectName: "myapp", upstream: "host.docker.internal:3000", env: "development", service: "web" });
    expect(inferred).toEqual({
      project: "myapp", service: "web", env: "development", driver: "bun", owner: "connect", port: 3000,
    });
  });

  it("scoped-алиас → driver docker, owner deploy", () => {
    const inferred = inferRouteMeta({ projectName: "myapp", upstream: "abc123-production-api:8000", env: "production", service: "api" });
    expect(inferred?.driver).toBe("docker");
    expect(inferred?.owner).toBe("deploy");
    expect(inferred?.port).toBe(8000);
  });

  it("localhost и 127.0.0.1 трактуются как host-маршрут", () => {
    expect(inferRouteMeta({ projectName: "p", upstream: "127.0.0.1:3000" })?.driver).toBe("bun");
    expect(inferRouteMeta({ projectName: "p", upstream: "localhost:3000" })?.driver).toBe("bun");
  });

  it("без имени проекта или upstream метаданные не выводятся", () => {
    expect(inferRouteMeta({ projectName: "", upstream: "web:3000" })).toBeNull();
    expect(inferRouteMeta({ projectName: "p", upstream: "" })).toBeNull();
  });
});
