import { describe, it, expect } from "bun:test";
import path from "node:path";
import os from "node:os";
import fs from "node:fs/promises";
import {
  parseCaddyProjectFile,
  matchContainerForRoute,
  formatDockerStatus,
  handleList,
  DockerContainerInfo,
} from "../src/commands/list.js";
import {
  stripAnsi,
  stringVisualWidth,
  padEndVisual,
  renderTable,
} from "../src/table.js";

describe("table utility", () => {
  it("strips ANSI escape sequences", () => {
    const colored = "\x1b[32m🟢 Up 2 hours\x1b[0m";
    expect(stripAnsi(colored)).toBe("🟢 Up 2 hours");
  });

  it("calculates visual column width correctly including emojis and colors", () => {
    expect(stringVisualWidth("cool-app")).toBe(8);
    // 🟢 takes 2 columns, space 1, "Up" 2 -> 5
    expect(stringVisualWidth("🟢 Up")).toBe(5);
    // With ANSI colors, visual width must match stripped text width
    const colored = "\x1b[32m🟢 Up 2 hours\x1b[0m";
    expect(stringVisualWidth(colored)).toBe(13);
  });

  it("pads strings with ANSI colors to exact visual width", () => {
    const colored = "\x1b[31m🔴 Offline\x1b[0m"; // visual width = 10
    const padded = padEndVisual(colored, 15);
    expect(stringVisualWidth(padded)).toBe(15);
    expect(padded.endsWith("     ")).toBe(true);
  });

  it("renders a beautifully aligned Unicode table", () => {
    const table = renderTable({
      headers: ["PROJECT", "STATUS"],
      rows: [
        ["cool-app", "\x1b[32m🟢 Up\x1b[0m"],
        ["landing", "\x1b[31m🔴 Offline\x1b[0m"],
      ],
    });

    expect(table).toContain("┌─");
    expect(table).toContain("PROJECT");
    expect(table).toContain("STATUS");
    expect(table).toContain("cool-app");
    expect(table).toContain("landing");
    expect(table).toContain("└─");

    // All lines in the rendered table must have the same visual width
    const lines = table.split("\n");
    const widths = lines.map((l) => stringVisualWidth(l));
    const firstWidth = widths[0];
    for (const w of widths) {
      expect(w).toBe(firstWidth);
    }
  });
});

describe("pegas ls / list dashboard parser", () => {
  it("parses single service project with www redirect", () => {
    const caddyContent = `# Auto-generated by Pegas for project: my-shop
# Do not edit manually; update pegas.json instead.

my-shop.com {
    encode gzip zstd
    reverse_proxy my-shop-web:3000
}

www.my-shop.com {
    redir https://my-shop.com{uri} permanent
}
`;
    const routes = parseCaddyProjectFile(caddyContent, "my-shop.caddy");
    expect(routes.length).toBe(1);
    expect(routes[0].projectName).toBe("my-shop");
    expect(routes[0].domains).toEqual(["my-shop.com", "www.my-shop.com"]);
    expect(routes[0].upstream).toBe("my-shop-web:3000");
  });

  it("parses multi-service project (web + api)", () => {
    const caddyContent = `# Auto-generated by Pegas for project: multi-app

multi-app.com {
    reverse_proxy multi-app-web:3000
}

api.multi-app.com {
    reverse_proxy multi-app-backend:8000
}
`;
    const routes = parseCaddyProjectFile(caddyContent, "multi-app.caddy");
    expect(routes.length).toBe(2);

    expect(routes[0].projectName).toBe("multi-app");
    expect(routes[0].domains).toEqual(["multi-app.com"]);
    expect(routes[0].upstream).toBe("multi-app-web:3000");

    expect(routes[1].projectName).toBe("multi-app");
    expect(routes[1].domains).toEqual(["api.multi-app.com"]);
    expect(routes[1].upstream).toBe("multi-app-backend:8000");
  });

  it("parses IDN Cyrillic domains correctly", () => {
    const caddyContent = `россия.рф {
    reverse_proxy russia-web:8080
}
`;
    const routes = parseCaddyProjectFile(caddyContent, "russia.caddy");
    expect(routes.length).toBe(1);
    expect(routes[0].projectName).toBe("russia");
    expect(routes[0].domains).toEqual(["россия.рф"]);
    expect(routes[0].upstream).toBe("russia-web:8080");
  });

  it("matches containers by exact name, prefix, and docker-compose labels", () => {
    const mockContainers: DockerContainerInfo[] = [
      {
        id: "abc12345",
        name: "my-shop-web-1",
        image: "node:18",
        state: "running",
        status: "Up 3 hours",
        networks: ["pegas-network"],
        composeProject: "my-shop",
        composeService: "web",
      },
      {
        id: "def67890",
        name: "standalone-api",
        image: "python:3.11",
        state: "exited",
        status: "Exited (0) 10m ago",
        networks: ["pegas-network"],
      },
    ];

    // Matched by prefix / compose service
    const match1 = matchContainerForRoute("my-shop-web:3000", "my-shop", mockContainers);
    expect(match1).not.toBeNull();
    expect(match1?.id).toBe("abc12345");

    // Matched by exact name
    const match2 = matchContainerForRoute("standalone-api:8000", "api", mockContainers);
    expect(match2).not.toBeNull();
    expect(match2?.id).toBe("def67890");

    // Unmatched
    const match3 = matchContainerForRoute("non-existent:5000", "ghost", mockContainers);
    expect(match3).toBeNull();
  });

  it("formats Docker status with colors and emojis", () => {
    const running: DockerContainerInfo = {
      id: "1",
      name: "c1",
      image: "img",
      state: "running",
      status: "Up 2 hours",
      networks: [],
    };
    const s1 = formatDockerStatus(running);
    expect(s1.state).toBe("running");
    expect(s1.displayStatus).toContain("🟢");
    expect(s1.displayStatus).toContain("Up 2 hours");

    const exited: DockerContainerInfo = {
      id: "2",
      name: "c2",
      image: "img",
      state: "exited",
      status: "Exited (1)",
      networks: [],
    };
    const s2 = formatDockerStatus(exited);
    expect(s2.state).toBe("exited");
    expect(s2.displayStatus).toContain("🔴");

    const none = formatDockerStatus(null);
    expect(none.state).toBe("offline");
    expect(none.displayStatus).toContain("🔴 Offline");
  });

  it("integrates handleList with mocked gateway directory and outputs JSON", async () => {
    const tmpGateway = await fs.mkdtemp(path.join(os.tmpdir(), "pegas-ls-gw-"));
    const confDir = path.join(tmpGateway, "conf.d");
    await fs.mkdir(confDir, { recursive: true });

    // Write a project route file
    const sampleRoute = `# Auto-generated by Pegas for project: demo-app

demo.com {
    reverse_proxy demo-app-web:3000
}
`;
    await fs.writeFile(path.join(confDir, "demo-app.caddy"), sampleRoute, "utf-8");

    // Capture console.log
    const logs: string[] = [];
    const origLog = console.log;
    console.log = (...args: any[]) => logs.push(args.join(" "));

    try {
      await handleList({ gatewayDir: tmpGateway, json: true });
      const output = logs.join("\n");
      const parsed = JSON.parse(output);

      expect(Array.isArray(parsed)).toBe(true);
      expect(parsed.length).toBe(1);
      expect(parsed[0].project).toBe("demo-app");
      expect(parsed[0].domains).toEqual(["demo.com"]);
      expect(parsed[0].upstream).toBe("demo-app-web:3000");
      expect(parsed[0].state).toBe("offline"); // no live docker container for this test fixture
    } finally {
      console.log = origLog;
      await fs.rm(tmpGateway, { recursive: true, force: true });
    }
  });
});
